/** Localized URL for a page: uk is the default at `/`, en lives under `/en/`. */
export function href(lang: Lang, page: Page | string = ''): string {
  const p = page ? `${page}/` : '';
  return lang === 'uk' ? `/${p}` : `/en/${p}`;
}

